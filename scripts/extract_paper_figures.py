import pymupdf

# Column boundaries in PDF points, taken from the header row word positions.
EDGES = [60, 158, 209, 261, 313, 365, 417, 468, 520, 612]
COLS = ["prompt", "1M/8L", "2.5M/8L", "8.3M/8L", "28M/8L", "33M/4L", "21M/1L",
        "33M/2L", "GPT2-XL(1.5B)"]
MODEL_COLS = COLS[1:]
FIGS = {9: (12, "factual"), 10: (13, "reasoning"), 11: (14, "context")}
FILL_TO_VERDICT = {
    (1.0, 0.5, 0.5): "incorrect",    # red
    (0.5, 1.0, 0.5): "correct",      # green
    (1.0, 0.969, 0.6): "partial",    # yellow
}
ROW_GAP = 10   # ~8pt between lines inside a row, ~13pt between rows

# Which released checkpoint each figure column corresponds to. Verified against
# each repo's config.json (num_layers / hidden_size) on 2026-10-29.
COLUMN_TO_REPO = {
    "1M/8L": "roneneldan/TinyStories-1M",
    "2.5M/8L": "roneneldan/TinyStories-3M",
    "8.3M/8L": "roneneldan/TinyStories-8M",
    "28M/8L": "roneneldan/TinyStories-28M",
    "33M/4L": "roneneldan/TinyStories-33M",
    "21M/1L": "roneneldan/TinyStories-1Layer-21M",
    "33M/2L": "roneneldan/TinyStories-2Layers-33M",
    "GPT2-XL(1.5B)": "gpt2-xl",
}

# Team 32 grading criteria. These are OURS, not the paper's: the paper only
# colour-codes its own outputs and never states an expected answer. Keyed by
# (figure, 1-based row) -> (capability, expected, auto_accept terms).
#
# `auto_accept` drives a CONSERVATIVE lexical screen and is deliberately empty
# where substring matching cannot settle the answer (negation, role tracking,
# or open-ended prompts). All of it was written before any model was run, and
# a lexical hit is NOT a substitute for human judgement.
