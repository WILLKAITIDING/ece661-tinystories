def col_of(x: float) -> int:
    for i in range(len(EDGES) - 1):
        if EDGES[i] <= x < EDGES[i + 1]:
            return i
    return len(COLS) - 1


def clean(s: str) -> str:
    """Join wrapped words and normalise the PDF's typographic quotes.

    The PDF renders both opening and closing quotes as U+201D. We normalise to
    ASCII quotes because that is what the GPT-Neo BPE tokenizer expects and
    almost certainly what the authors fed the model; `text_pdf_raw` keeps the
    unmodified string so the change is auditable.
    """
    s = re.sub(r"(\w)-\s+(\w)", r"\1\2", s)
    s = s.replace("”", '"').replace("“", '"').replace("’", "'")
    return re.sub(r"\s+", " ", s).strip()


def _rows_from_lines(lines: dict, ys: list[int]) -> list[list[int]]:
    rows, cur = [], [ys[0]]
    for prev, y in zip(ys, ys[1:]):
        if y - prev > ROW_GAP:
            rows.append(cur)
            cur = [y]
        else:
            cur.append(y)
    rows.append(cur)
    return rows


def extract_figure(page) -> list[dict]:
    """Return one dict per table row: prompt text plus each model's completion."""
    lines: dict[tuple[int, int], list[tuple[float, str]]] = {}
    for x0, y0, _x1, _y1, word, *_ in page.get_text("words"):
        lines.setdefault((round(y0), col_of(x0)), []).append((x0, word))
    ys = sorted({y for y, _ in lines})

    # The header row sits at a different y on each page, so find it.
    header_y = next(
        y for y in ys
        if " ".join(w for _, w in sorted(lines.get((y, 0), []))) == "Prompt"
    )
    after = [y for y in ys if y > header_y]
    first_data_y = next(b for a, b in zip(after, after[1:]) if b - a > ROW_GAP)
    ys = [y for y in ys if y >= first_data_y]

    entries = []
    for row_ys in _rows_from_lines(lines, ys):
        cells = {c: [] for c in range(len(COLS))}
        for y in row_ys:
            for c in range(len(COLS)):
                if (y, c) in lines:
                    cells[c].append(" ".join(w for _, w in sorted(lines[(y, c)])))
        raw = {COLS[c]: " ".join(cells[c]).strip() for c in range(len(COLS))}
        if raw["prompt"] and not raw["prompt"].startswith("Figure"):
            entries.append(raw)
    return entries


def extract_verdicts(page, n_rows: int) -> list[dict[str, str]]:
    """Recover the green/yellow/red verdicts from the cell background fills."""
    rects = []
    for drawing in page.get_drawings():
        fill = drawing.get("fill")
        if not fill:
            continue
        key = tuple(round(v, 3) for v in fill)
        if key in FILL_TO_VERDICT:
            r = drawing["rect"]
            # Use the CENTRE x: a cell's rectangle starts slightly left of its
            # text, so bucketing by the left edge is off by one column.
            rects.append((r.y0, (r.x0 + r.x1) / 2, FILL_TO_VERDICT[key]))
    rects.sort()

    rows, cur = [], [rects[0]]
    for prev, cur_rect in zip(rects, rects[1:]):
        if cur_rect[0] - prev[0] > 3:
            rows.append(cur)
            cur = [cur_rect]
        else:
            cur.append(cur_rect)
    rows.append(cur)

    if len(rows) != n_rows:
        raise ValueError(f"found {len(rows)} verdict rows, expected {n_rows}")
    out = []
    for row in rows:
        verdicts = {COLS[col_of(cx)]: verdict for _, cx, verdict in row}
        if "prompt" in verdicts or len(verdicts) != len(MODEL_COLS):
            raise ValueError(f"bad verdict row: {verdicts}")
        out.append(verdicts)
    return out


def main(pdf_path: str, repo_root: Path) -> int:
    pdf = Path(pdf_path)
    sha = hashlib.sha256(pdf.read_bytes()).hexdigest()
    doc = pymupdf.open(pdf)

    prompts, reference = [], []
    for fig, (pageno, category) in FIGS.items():
        page = doc[pageno]
        raw_rows = extract_figure(page)
        verdicts = extract_verdicts(page, len(raw_rows))
        for i, (raw, verdict) in enumerate(zip(raw_rows, verdicts), start=1):
            pid = f"fig{fig}_{i:02d}"
            capability, expected, auto_accept = ANNOTATIONS[(fig, i)]
            prompts.append({
                "id": pid,
                "origin": "paper",
                "figure": fig,
                "category": category,
                "source_ref": f"arXiv:2305.07759v2 Figure {fig}, row {i} (p.{pageno + 1})",
                "text": clean(raw["prompt"]),
                "text_pdf_raw": raw["prompt"],
                "capability": capability,
                "expected": expected,
                "criterion_author": "team32",
                "auto_accept": auto_accept,
            })
            reference.append({
                "id": pid,
                "figure": fig,
                "category": category,
                "completions": {m: clean(raw[m]) for m in MODEL_COLS},
                "paper_verdicts": verdict,
            })

    provenance = {
        "paper": "TinyStories: How Small Can Language Models Be and Still Speak Coherent English?",
        "authors": "Eldan and Li",
        "arxiv_id": "2305.07759",
        "version": "v2",
        "pdf_sha256": sha,
        "extracted_on": date.today().isoformat(),
        "extracted_by": "scripts/extract_paper_figures.py",
    }

    prompt_file = repo_root / "data" / "prompts" / "paper_figures_9_11.json"
    ref_file = repo_root / "data" / "reference" / "paper_figure_completions.json"

    prompt_file.parent.mkdir(parents=True, exist_ok=True)
    ref_file.parent.mkdir(parents=True, exist_ok=True)

    json.dump({
        "schema_version": "1.0",
        "name": "paper_figures_9_11",
        "description": (
            "Prompts of Figures 9-11 of the TinyStories paper, recovered from "
            "the published PDF by layout-aware extraction. 'capability' and "
            "'expected' are Team 32 grading criteria, not the paper's."
        ),
        "source": provenance,
        "notes": [
            "Quotes normalised from the PDF's U+201D to ASCII; text_pdf_raw keeps the original.",
            "Hyphens inserted by the figure's line wrapping were removed.",
            "The paper states no expected answers; it only colour-codes its own outputs.",
            "'auto_accept' drives a conservative lexical screen, NOT human judgement; "
            "it is empty where substring matching cannot settle the answer.",
        ],
        "prompts": prompts,
    }, prompt_file.open("w"), indent=2, ensure_ascii=False)

    json.dump({
        "schema_version": "1.0",
        "description": (
            "The TinyStories paper's OWN published completions and colour-coded "
            "verdicts. These were NOT generated by Team 32 and must always be "
            "labelled as the paper's results when displayed."
        ),
        "source": provenance,
        "verdict_legend": {"correct": "green", "partial": "yellow", "incorrect": "red"},
        "column_to_checkpoint": COLUMN_TO_REPO,
        "rows": reference,
    }, ref_file.open("w"), indent=2, ensure_ascii=False)

    print(f"Wrote {len(prompts)} prompts -> {prompt_file.relative_to(repo_root)}")
    print(f"Wrote {len(reference)} reference rows -> {ref_file.relative_to(repo_root)}")
    for fig in FIGS:
        n = sum(1 for p in prompts if p["figure"] == fig)
        print(f"   Figure {fig} ({FIGS[fig][1]}): {n} prompts")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        raise SystemExit(2)
    raise SystemExit(main(sys.argv[1], Path(__file__).resolve().parent.parent))
