#!/usr/bin/env python
"""Extract the prompts, completions and verdicts of TinyStories Figures 9-11.

    python scripts/extract_paper_figures.py path/to/2305.07759v2.pdf

Why this is not a simple text dump
----------------------------------
Reading the PDF's text in order is AMBIGUOUS: a wrapped prompt cell and the
first completion cell interleave, so you cannot tell where the prompt ends.
For example Figure 10 row 9 reads as either

    "... Ben knocked on the door," | "but it was too late. ..."      (correct)
    "... Ben knocked on the door, but it was" | "too late. ..."      (wrong)

So cells are assigned to columns by x-coordinate and to rows by vertical gap.
The paper's green/yellow/red verdicts are cell BACKGROUND fills, recovered the
same way.

Validation (all checked by tests/test_task2.py):
  * 72 / 72 / 48 coloured cells = rows x 8 models for Figures 9 / 10 / 11.
  * "the model with 1M parameters and 8 layers fails to answer any factual
    prompt correctly" (p.9)  -> 1M/8L has 0 'correct' in Figure 9.
  * "the model that has only 1 layer does not get any consistency prompt
    right" (p.10)            -> 21M/1L has 0 'correct' in Figure 11.
  * Verdicts match a visual render of the figure for Figure 9 rows 1-3.

Outputs:
  data/prompts/paper_figures_9_11.json      prompts + our grading criteria
  data/reference/paper_figure_completions.json
                                            the paper's OWN published outputs
                                            and verdicts. NOT generated by us.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from datetime import date
